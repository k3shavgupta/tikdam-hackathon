import {spawnSync} from 'node:child_process';
import {readFile,writeFile,rename,cp,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';

for(const args of [['run','build:app'],['--prefix','landing','run','build']]){
 const result=spawnSync('npm',args,{stdio:'inherit'});
 if(result.status!==0)process.exit(result.status||1);
}
await rename('dist/index.html','dist/app.html');
await cp('landing/out','dist',{recursive:true});
const hashes=new Set();
async function scan(dir){
 for(const entry of await readdir(dir,{withFileTypes:true})){
  const file=path.join(dir,entry.name);
  if(entry.isDirectory())await scan(file);
  else if(file.endsWith('.html')){
   const html=await readFile(file,'utf8');
   for(const match of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)){
    if(!/\bsrc\s*=/.test(match[1])&&match[2])hashes.add("'sha256-"+createHash('sha256').update(match[2]).digest('base64')+"'");
   }
  }
 }
}
await scan('landing/out');
await writeFile('worker/landing-csp.mjs',`// Generated by scripts/build-site.mjs. Exact hashes of exported inline scripts.\nexport const landingScriptHashes = ${JSON.stringify([...hashes].sort(),null,2)};\n`);
console.log(`Combined homepage and app. Allowed ${hashes.size} exact inline script hashes.`);
